-- Geld/Reputation und Gebietsverwaltung nur Administrator/Master.
create or replace function public.admin_set_player(p_target uuid,p_money bigint default null,p_reputation integer default null)
returns json language plpgsql security definer set search_path=public as $$
declare m bigint; rep integer;
begin
  if public.admin_rank() < 3 then raise exception 'administrator_required'; end if;
  update public.profiles set money=case when p_money is null then money else greatest(p_money,0) end,
    reputation=case when p_reputation is null then reputation else greatest(p_reputation,0) end,updated_at=now()
  where id=p_target returning money,reputation into m,rep;
  if not found then raise exception 'player_not_found'; end if;
  insert into public.admin_logs(admin_id,action,target_user_id,details)
  values(auth.uid(),'set_player',p_target,json_build_object('money',p_money,'reputation',p_reputation));
  return json_build_object('success',true,'money',m,'reputation',rep);
end;
$$;
grant execute on function public.admin_set_player(uuid,bigint,integer) to authenticated;

