-- Spielzugriff inkl. Kick, Mute und Bann.
create or replace function public.player_access_status()
returns json language plpgsql security definer set search_path=public as $$
declare s public.player_sanctions; r text:=public.admin_role();
begin
  select * into s from public.player_sanctions where user_id=auth.uid();
  if s.banned_until is not null and s.banned_until > now() then
    return json_build_object('allowed',false,'type','ban','until',s.banned_until,'reason',s.ban_reason);
  end if;
  if s.kicked_until is not null and s.kicked_until > now() then
    return json_build_object('allowed',false,'type','kick','until',s.kicked_until,'reason','Du wurdest gekickt.');
  end if;
  return json_build_object('allowed',true,'role',r,'muted',s.muted_until is not null and s.muted_until > now(),'muted_until',s.muted_until,'mute_reason',s.mute_reason);
end;
$$;
grant execute on function public.player_access_status() to authenticated;

create or replace function public.player_chat_status()
returns json language plpgsql security definer set search_path=public as $$
declare s public.player_sanctions;
begin
  select * into s from public.player_sanctions where user_id=auth.uid();
  if s.muted_until is not null and s.muted_until > now() then
    return json_build_object('allowed',false,'until',s.muted_until,'reason',s.mute_reason);
  end if;
  return json_build_object('allowed',true);
end;
$$;
grant execute on function public.player_chat_status() to authenticated;

