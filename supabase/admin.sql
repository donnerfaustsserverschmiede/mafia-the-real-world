-- Bann: Moderator maximal 24h. Administrator/Master dürfen auch dauerhaft bannen (p_duration_minutes=0).
create or replace function public.admin_ban(p_target uuid,p_duration_minutes integer,p_reason text default 'Kein Grund angegeben')
returns json language plpgsql security definer set search_path=public as $$
declare actor_role text:=public.admin_role(); until_at timestamptz;
begin
  if actor_role not in ('moderator','administrator','master') then raise exception 'moderator_required'; end if;
  if p_target=auth.uid() then raise exception 'cannot_sanction_self'; end if;
  if p_duration_minutes < 0 then raise exception 'invalid_duration'; end if;
  if actor_role='moderator' and p_duration_minutes > 1440 then raise exception 'moderator_max_24h'; end if;
  if p_duration_minutes=0 then
    if actor_role not in ('administrator','master') then raise exception 'administrator_required_for_permanent_ban'; end if;
    until_at:=now()+interval '100 years';
  else until_at:=now()+make_interval(mins=>p_duration_minutes); end if;
  insert into public.player_sanctions(user_id,banned_until,ban_reason,updated_at) values(p_target,until_at,p_reason,now())
  on conflict(user_id) do update set banned_until=excluded.banned_until,ban_reason=excluded.ban_reason,updated_at=now();
  insert into public.admin_logs(admin_id,action,target_user_id,details)
  values(auth.uid(),'ban',p_target,json_build_object('minutes',p_duration_minutes,'permanent',p_duration_minutes=0,'reason',p_reason));
  return json_build_object('success',true,'banned_until',until_at,'permanent',p_duration_minutes=0);
end;
$$;
grant execute on function public.admin_ban(uuid,integer,text) to authenticated;

